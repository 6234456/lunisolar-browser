"""Convert the pinned, licensed DILA SQL snapshot without executing SQL/code."""
import hashlib
import json
import re
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
archive = ROOT / 'vendor/dila/authority_time_chinese.2012-02.zip'
expected_sha = '53937ef60dbe8061a2e56aa8ef2feaaa08a1fa4d1a62a117a4b9932046f55530'
assert hashlib.sha256(archive.read_bytes()).hexdigest() == expected_sha, 'Unexpected historical source archive'
with zipfile.ZipFile(archive) as z:
    sql = z.read('authority_time_chinese/authority_time_chinese.sql').decode('utf-8')
token = re.compile(r"\s*(NULL|-?\d+|'(?:\\.|[^'\\])*'|[(),])", re.S)

def rows(table):
    result = []
    for match in re.finditer(r'INSERT INTO `' + re.escape(table) + r'` VALUES (.*?);\n', sql, re.S):
        text = match[1]
        pos = 0
        row = None
        while pos < len(text):
            m = token.match(text, pos)
            if not m:
                raise ValueError(f'Unrecognized SQL value in {table} at {pos}')
            pos = m.end()
            value = m[1]
            if value == '(':
                assert row is None
                row = []
            elif value == ')':
                assert row is not None
                result.append(row)
                row = None
            elif value == ',':
                pass
            else:
                assert row is not None
                if value.startswith("'"):
                    value = re.sub(r'\\(.)', lambda x: {'n':'\n','r':'\r','t':'\t','0':'\0'}.get(x[1],x[1]), value[1:-1])
                else:
                    value = None if value == 'NULL' else int(value)
                row.append(value)
    assert result, table
    return result

def names(table):
    return {r[0]: r[1] for r in rows(table) if r[2] == 0 and r[3] == 1}

dynasties = names('t_dynasty_names')
emperors = names('t_emperor_names')
era_names = names('t_era_names')
emperor_dynasty = dict(rows('t_emperor'))
eras = {}
for era_id, emperor_id in rows('t_era'):
    dynasty_id = emperor_dynasty[emperor_id]
    eras[era_id] = {'id':era_id, 'name':era_names.get(era_id,''),
        'emperor':emperors.get(emperor_id,''), 'dynastyId':dynasty_id,
        'dynasty':dynasties.get(dynasty_id,'')}

# Keep original row IDs, actual intervals and split-month offsets. Never assume
# an era begins on lunar day 1 or a historical year begins in the first month.
months = []
for r in rows('t_month'):
    ident, year, month, name, leap, era, first, last, ganzhi, start, status, eclipse = r
    assert first <= last and start >= 1 and era in eras
    months.append([ident,era,year,month,name,leap,first,last,start,status])
months.sort(key=lambda r:(r[6],r[7],r[0]))
used = {r[1] for r in months}
data = {'source':{'id':'dila-time-chinese-2012-02',
    'title':'DDBC / DILA Chinese Time Authority Database',
    'url':'https://authority.dila.edu.tw/docs/open_content/download.php',
    'archiveUrl':'https://authority.dila.edu.tw/downloads/authority_time_chinese.2012-02.zip',
    'sha256':hashlib.sha256(archive.read_bytes()).hexdigest(),
    'license':'CC-BY-SA-3.0',
    'licenseUrl':'https://creativecommons.org/licenses/by-sa/3.0/',
    'limitations':['Era boundary status fields are incomplete in the source.',
        'Some peripheral dynasties are absent; this is a sourced reconstruction, not a guarantee of historical certainty.']},
    'columns':['id','eraId','eraYear','month','monthName','isLeap','firstJdn','lastJdn','startDay','status'],
    'eras':{k:v for k,v in eras.items() if k in used}, 'months':months}
encoded = json.dumps(data,ensure_ascii=False,separators=(',',':')).replace('</','<\\/')
output = '/* Derived from DDBC/DILA, CC BY-SA 3.0. See vendor/dila; generated by scripts/build-history.py. */\n'
output += 'globalThis.LunisolarHistoricalData = ' + encoded + ';\n'
(ROOT/'data/dila-history.js').write_text(output)
print(f'Built {len(months)} month segments and {len(used)} eras; JDN {min(r[6] for r in months)}..{max(r[7] for r in months)}')
